/**
 * The two hero portraits.
 *
 * Both frames arrive already registered — same framing, same eyeline, same 3:4
 * aspect — so there is deliberately no crop, shift or zoom. The hero container
 * is 3:4 to match, leaving object-fit: cover nothing to trim.
 *
 * Output filenames carry a content hash. Without one, swapping the source
 * images changes nothing a reader sees: the URL stays the same, so Next's
 * image optimiser keeps serving the variant it cached under that URL and the
 * browser keeps its own copy too. A hash in the name busts both, every time,
 * without anyone having to remember to clear a cache.
 */
import { createHash } from "node:crypto";
import { readdir, unlink, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const OUT_DIR = "public/media/portrait";

const SOURCES = [
  { key: "city", src: "/Users/henrywall/Desktop/ME/box.jpg" },
  { key: "camp", src: "/Users/henrywall/Desktop/ME/meee.jpg" },
];

// Clear previous output so stale hashes do not accumulate in the repo.
for (const f of await readdir(OUT_DIR).catch(() => [])) {
  if (f.endsWith(".webp")) await unlink(path.join(OUT_DIR, f));
}

const written = [];

for (const { key, src } of SOURCES) {
  const buf = await sharp(src)
    .rotate()
    .resize({ width: 1400, withoutEnlargement: true })
    .webp({ quality: 84, effort: 6 })
    .toBuffer();

  const hash = createHash("sha256").update(buf).digest("hex").slice(0, 8);
  const name = `hal-${key}.${hash}.webp`;
  await writeFile(path.join(OUT_DIR, name), buf);

  const meta = await sharp(buf).metadata();
  written.push({ key, name });
  console.log(
    `${name}  ${meta.width}x${meta.height}  ${(buf.length / 1024).toFixed(0)}KB  aspect ${(meta.width / meta.height).toFixed(4)}`,
  );
}

const module_ = `// GENERATED by scripts/crop-portraits.mjs — do not edit by hand.
// Filenames are content-hashed, so changing a source image changes its URL and
// no cache anywhere can serve the previous one.

export const portraits = {
${written.map((w) => `  ${w.key}: "/media/portrait/${w.name}",`).join("\n")}
} as const;
`;
await writeFile("content/portraits.ts", module_);
console.log("wrote content/portraits.ts");
