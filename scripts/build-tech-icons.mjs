/**
 * Extracts only the icon paths this site actually uses into a local module.
 *
 * simple-icons stays a devDependency: importing it at runtime would put a few
 * thousand unused icons in reach of the bundler. This emits a flat map of the
 * twenty-odd we reference, so the shipped cost is the paths themselves.
 */
import { writeFile } from "node:fs/promises";
import * as si from "simple-icons";

const WANT = [
  "swift",
  // The Daily Canon's stack
  "nextdotjs", "typescript", "tailwindcss", "supabase", "vercel",
  "apple", "anthropic", "stripe", "redis", "capacitor", "react",
  // Hal's engineering stack
  "python", "apachespark", "databricks", "apachekafka", "postgresql",
  "fastapi", "nodedotjs", "javascript", "html5", "css3", "git",
  "docker", "githubactions", "pandas", "numpy",
];

const get = (slug) => {
  const key = "si" + slug.charAt(0).toUpperCase() + slug.slice(1);
  return si[key] ?? null;
};

const found = [];
const missing = [];

for (const slug of WANT) {
  const icon = get(slug);
  if (icon) found.push([slug, icon]);
  else missing.push(slug);
}

const body = found
  .map(([slug, i]) =>
    `  "${slug}": { title: ${JSON.stringify(i.title)}, hex: "#${i.hex}", path: ${JSON.stringify(i.path)} },`,
  )
  .join("\n");

await writeFile(
  "content/tech-icons.ts",
  `// GENERATED by scripts/build-tech-icons.mjs — do not edit by hand.
// Source: simple-icons (CC0). Only the icons this site references are included.

export interface TechIcon {
  title: string;
  /** The brand's own colour. Used sparingly; most surfaces ink these with currentColor. */
  hex: string;
  path: string;
}

export const techIcons: Record<string, TechIcon> = {
${body}
};

export type TechSlug = keyof typeof techIcons;
`,
);

console.log(`wrote ${found.length} icons`);
if (missing.length) console.log(`no icon for: ${missing.join(", ")}`);
